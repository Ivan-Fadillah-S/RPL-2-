    // FUNGSI UNTUK MEMBATASI HAK AKSES MENU
private void aturHakAkses() {
    if (roleUser == null) return;

    if (roleUser.equalsIgnoreCase("Kasir")) {
        jMenu1.setEnabled(false);        // Menu Master dikunci untuk kasir
        menuPembelian.setEnabled(false); // Kasir tidak boleh akses pembelian
    } else if (roleUser.equalsIgnoreCase("Gudang")) {
        menuPenjualan.setEnabled(false); // Gudang tidak boleh akses penjualan
        jMenu3.setEnabled(false);        // Menu Laporan dikunci untuk gudang
    }
}
    
