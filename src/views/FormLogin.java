    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtUsername.getText();
        String password = new String(txtPassword.getPassword());

    // Validasi jika kolom kosong
        if (username.isEmpty() || password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Username dan Password tidak boleh kosong!");
            return;
        }

        try {
            java.sql.Connection conn = config.Koneksi.getConnection();
            String sql = "SELECT * FROM users WHERE username = ? AND password = ?";
            java.sql.PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, username);
            ps.setString(2, password);
            java.sql.ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                String namaLengkap = rs.getString("nama_lengkap");
                String role = rs.getString("role");
                int idUser = rs.getInt("id_user");

                javax.swing.JOptionPane.showMessageDialog(this, "Login Berhasil! Selamat datang, " + namaLengkap);

                // Membuka Menu Utama dengan membawa data role dan id user
                new MenuUtama(role, idUser).setVisible(true);
                this.dispose(); // Menutup form login
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Username atau Password salah!");
            }
        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error Database: " + e.getMessage());
        }    
    }//GEN-LAST:event_btnLoginActionPerformed

