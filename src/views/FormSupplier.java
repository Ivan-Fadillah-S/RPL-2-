    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try {
            Connection conn = Koneksi.getConnection();
            String sql = "INSERT INTO supplier (nama_supplier, no_telepon, alamat) VALUES (?, ?, ?)";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, txtNamaSupplier.getText());
            ps.setString(2, txtTelepon.getText());
            ps.setString(3, txtAlamat.getText());
            
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data Supplier Berhasil Disimpan!");
            loadData();
            kosongkanForm();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal Simpan: " + e.getMessage());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        try {
            Connection conn = Koneksi.getConnection();
            String sql = "UPDATE supplier SET nama_supplier=?, no_telepon=?, alamat=? WHERE id_supplier=?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, txtNamaSupplier.getText());
            ps.setString(2, txtTelepon.getText());
            ps.setString(3, txtAlamat.getText());
            ps.setInt(4, Integer.parseInt(txtIdSupplier.getText()));
            
            ps.executeUpdate();
            JOptionPane.showMessageDialog(this, "Data Supplier Berhasil Diubah!");
            loadData();
            kosongkanForm();
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal Edit: " + e.getMessage());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int confirm = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus supplier ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Connection conn = Koneksi.getConnection();
                String sql = "DELETE FROM supplier WHERE id_supplier=?";
                PreparedStatement ps = conn.prepareStatement(sql);
                ps.setInt(1, Integer.parseInt(txtIdSupplier.getText()));
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "Data Berhasil Dihapus!");
                loadData();
                kosongkanForm();
            } catch (SQLException e) {
                JOptionPane.showMessageDialog(this, "Gagal Hapus: " + e.getMessage());
            }
        }        // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

