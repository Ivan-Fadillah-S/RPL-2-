    // 2. Fungsi Menghitung Total Harga Belanjaan Secara Otomatis
    private void hitungTotal() {
        int total = 0;
        int jumlahBaris = tableKeranjang.getRowCount();
        for (int i = 0; i < jumlahBaris; i++) {
            int subtotal = Integer.parseInt(tableKeranjang.getValueAt(i, 4).toString());
            total += subtotal;
        }
        lblTotal.setText("Rp " + total);
    }

