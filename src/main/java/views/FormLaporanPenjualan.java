    private void loadDataLaporan() {
        modelLaporan = new DefaultTableModel();
        modelLaporan.addColumn("No Faktur");
        modelLaporan.addColumn("Tanggal");
        modelLaporan.addColumn("ID Pelanggan");
        modelLaporan.addColumn("ID User");
        modelLaporan.addColumn("Total Bayar");
        modelLaporan.addColumn("Jumlah Uang");
        modelLaporan.addColumn("Kembalian");
        
        tableLaporan.setModel(modelLaporan);
        modelLaporan.setRowCount(0);

        try {
            Connection conn = Koneksi.getConnection();
            Statement st = conn.createStatement();
            String sql = "SELECT * FROM penjualan ORDER BY tanggal DESC";
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                modelLaporan.addRow(new Object[]{
                    rs.getString("no_faktur_jual"),
                    rs.getString("tanggal"),
                    rs.getInt("id_pelanggan"),
                    rs.getInt("id_user"),
                    rs.getDouble("total_bayar"),
                    rs.getDouble("jumlah_uang"),
                    rs.getDouble("kembalian")
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat laporan penjualan: " + e.getMessage());
        }
    }


