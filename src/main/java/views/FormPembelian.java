    // 2. Fungsi Hitung Total Belanjaan Pembelian
    private void hitungTotal() {
        int total = 0;
        int jumlahBaris = tableKeranjangBeli.getRowCount();
        for (int i = 0; i < jumlahBaris; i++) {
            int subtotal = Integer.parseInt(tableKeranjangBeli.getValueAt(i, 4).toString());
            total += subtotal;
        }
        lblTotalBeli.setText("Rp " + total);
    }

