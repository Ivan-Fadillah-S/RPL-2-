    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        try {
            String idBarang = txtIdBarang.getText();
            String namaBarang = txtNamaBarang.getText();
            int hargaBeli = Integer.parseInt(txtHargaBeli.getText());
            int qty = Integer.parseInt(txtJumlah.getText());
            int subtotal = hargaBeli * qty;

            modelKeranjangBeli.addRow(new Object[]{idBarang, namaBarang, hargaBeli, qty, subtotal});
            hitungTotal();
            
            // Bersihkan input barang
            txtIdBarang.setText("");
            txtNamaBarang.setText("");
            txtHargaBeli.setText("");
            txtJumlah.setText("");
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Pastikan harga dan jumlah terisi dengan angka yang benar!");
        }     // TODO add your handling code here:
    }//GEN-LAST:event_btnTambahActionPerformed

