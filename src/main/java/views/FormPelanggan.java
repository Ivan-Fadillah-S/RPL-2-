    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
try {
    Connection conn = Koneksi.getConnection();
    String sql = "INSERT INTO pelanggan (nama_pelanggan, no_telepon, alamat) VALUES (?, ?, ?)";
    PreparedStatement ps = conn.prepareStatement(sql);
    ps.setString(1, txtNamaPelanggan.getText());
    ps.setString(2, txtTelepon.getText());
    ps.setString(3, txtAlamat.getText());

    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Data Pelanggan Berhasil Disimpan!");
    loadData();
    kosongkanForm();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, "Gagal Simpan: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        try {
    Connection conn = Koneksi.getConnection();
    String sql = "UPDATE pelanggan SET nama_pelanggan=?, no_telepon=?, alamat=? WHERE id_pelanggan=?";
    PreparedStatement ps = conn.prepareStatement(sql);
    ps.setString(1, txtNamaPelanggan.getText());
    ps.setString(2, txtTelepon.getText());
    ps.setString(3, txtAlamat.getText());
    ps.setInt(4, Integer.parseInt(txtIdPelanggan.getText()));

    ps.executeUpdate();
    JOptionPane.showMessageDialog(this, "Data Pelanggan Berhasil Diubah!");
    loadData();
    kosongkanForm();
} catch (SQLException e) {
    JOptionPane.showMessageDialog(this, "Gagal Edit: " + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int confirm = JOptionPane.showConfirmDialog(this, "Yakin ingin menghapus pelanggan ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
if (confirm == JOptionPane.YES_OPTION) {
    try {
        Connection conn = Koneksi.getConnection();
        String sql = "DELETE FROM pelanggan WHERE id_pelanggan=?";
        PreparedStatement ps = conn.prepareStatement(sql);
        ps.setInt(1, Integer.parseInt(txtIdPelanggan.getText()));
        ps.executeUpdate();
        JOptionPane.showMessageDialog(this, "Data Berhasil Dihapus!");
        loadData();
        kosongkanForm();
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Gagal Hapus: " + e.getMessage());
    }
}        // TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

